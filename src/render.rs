//! Render a snapshot as a hosts-file block, plus a stable content hash for
//! HTTP caching.

use crate::probe::Snapshot;

pub const VERSION: &str = env!("CARGO_PKG_VERSION");
pub const BLOCK_BEGIN: &str = "# >>> github-hosts";
pub const BLOCK_END: &str = "# <<< github-hosts <<<";

/// Presentation order: the page itself first, then the things it loads.
const ORDER: &[&str] = &[
    "github.com",
    "www.github.com",
    "gist.github.com",
    "github.githubassets.com",
    "api.github.com",
    "raw.githubusercontent.com",
    "avatars.githubusercontent.com",
    "camo.githubusercontent.com",
    "user-images.githubusercontent.com",
    "objects.githubusercontent.com",
    "release-assets.githubusercontent.com",
    "media.githubusercontent.com",
    "codeload.github.com",
    "github.io",
];

pub fn render_hosts(snap: &Snapshot, mode: &str) -> String {
    let auto = mode == "auto";
    let mut out = String::with_capacity(2048);
    let stamp = snap.generated_at.format("%Y-%m-%dT%H:%M:%S%:z");

    out.push_str(&format!(
        "{BLOCK_BEGIN} :: {stamp} :: mode={mode} :: v{VERSION} >>>\n"
    ));
    out.push_str("# Generated by github-hosts. Do not edit inside this block.\n");
    out.push_str(&format!(
        "# endpoints {}/{} verified | git {} | cycle {} | probe {}ms\n",
        snap.verified,
        snap.expected,
        if snap.git_ok { "ok" } else { "FAIL" },
        snap.cycle_id,
        snap.elapsed_ms
    ));

    // In `auto` mode a host whose verified IP is already among the system
    // resolver's answers is left alone: pinning it would only add staleness.
    let dns_has = |host: &str, ip: &str| -> bool {
        snap.dns
            .get(host)
            .map(|v| v.iter().any(|x| x == ip))
            .unwrap_or(false)
    };

    let mut printed: Vec<&str> = Vec::new();
    let mut skipped = 0usize;

    for host in ORDER {
        if let Some(e) = snap.endpoints.iter().find(|e| e.host == *host) {
            if !e.verified {
                continue;
            }
            if auto && dns_has(&e.host, &e.ip) {
                out.push_str(&format!(
                    "# {:42} DNS already returns {}; not pinned\n",
                    e.host, e.ip
                ));
                skipped += 1;
                continue;
            }
            out.push_str(&format!(
                "{:<16} {:<42} # {:>6.0}ms\n",
                e.ip, e.host, e.latency_ms
            ));
            printed.push(host);
        }
    }
    // any verified host not in ORDER yet
    for e in &snap.endpoints {
        if !e.verified || printed.contains(&e.host.as_str()) {
            continue;
        }
        if auto && dns_has(&e.host, &e.ip) {
            out.push_str(&format!(
                "# {:42} DNS already returns {}; not pinned\n",
                e.host, e.ip
            ));
            skipped += 1;
            continue;
        }
        out.push_str(&format!(
            "{:<16} {:<42} # {:>6.0}ms\n",
            e.ip, e.host, e.latency_ms
        ));
    }
    if auto && skipped > 0 {
        out.push_str(&format!("# {skipped} host(s) left to system DNS\n"));
    }

    for host in &snap.unverified {
        out.push_str(&format!(
            "# unverified (falls back to system DNS): {host}\n"
        ));
    }
    if !snap.git_ok {
        out.push_str(&format!(
            "# WARNING: git smart-http not validated: {}\n",
            snap.git_detail
        ));
    }
    out.push_str(BLOCK_END);
    out.push('\n');
    out
}

/// FNV-1a 64: stable across processes, good enough for an ETag.
pub fn content_hash(body: &str) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in body.as_bytes() {
        h ^= *b as u64;
        h = h.wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!("\"{h:016x}\"")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hash_is_stable_and_distinguishes_content() {
        let a = content_hash("# >>> github-hosts\ngithub.com\n");
        let b = content_hash("# >>> github-hosts\ngithub.com\n");
        let c = content_hash("# >>> github-hosts\nraw.githubusercontent.com\n");
        assert_eq!(a, b, "same input must produce the same ETag");
        assert_ne!(a, c);
    }

    #[test]
    fn hash_is_a_quoted_strong_etag() {
        let h = content_hash("x");
        assert!(h.starts_with('"') && h.ends_with('"'));
        assert_eq!(h.len(), 18); // 16 hex digits plus two quotes
    }
}
